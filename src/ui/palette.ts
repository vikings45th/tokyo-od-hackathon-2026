/**
 * 配色と色の5段ビン。③UI担当が所有する。
 *
 * 🔴 ビンは「分位」ではなく「固定値」。年度やシナリオを変えても色の意味を動かさないため。
 *    値の根拠は docs/17-setup-request.md §4（588セルの実測分布）。
 *    旧契約の [0,10,25,40,60] では上位2色がほぼ使われず地図が単色になる。
 *
 * ── 2026-08-23 配色を2色に変更 ──
 * 画面の問いを「入れない子がどれくらい出るか」から「入りやすいのはどこか」に変えたので、
 * 青1色の濃淡（＝量だけ）から、**色相で良し悪しを分ける2色**にした。
 *   ビン0（〜3%＝ほぼ全員入れる） … 青。ここだけ色相が違う。--accent と同じ値
 *   ビン1〜4（不足の量）          … 暖色の濃淡
 *
 * 🔴 スコアは 0〜100 で負値が無く、自然なゼロ交差点が無い（588セル中137が score 0、
 *    p50=5.5 / p90=15.8 / max=50.8）。だから両端対称＋中央グレーの正統な発散配色にはしない。
 *    「良い側を1色で立てて、不足側は濃淡」がこのデータの形に合う。
 * 🔴 暖色は橙まで振らないこと。Series.tsx の「入れる数」が #b06a00 で、同じ画面で
 *    橙が2つの意味を持つ。彩度の高い赤も避ける（--crit #c23434 が危機の予約色）。
 *
 * `dataviz` スキルの validate_palette.js による実測（2026-08-23）：
 *   CVD 全ペア分離  ライト 最悪 #70331f↔#9c5238 ΔE 11.9 (protan)
 *                   ダーク 最悪 #c99a72↔#b3784d ΔE 9.6 (deutan)   ← 目標8以上を PASS
 *                   最悪ペアがどちらも「暖色ランプ内の隣接段」なので、
 *                   青と暖色（＝良し悪し）の区別はこれよりさらに大きい
 *   暖色4段 --ordinal   ライト・ダークとも全チェック PASS
 *                       （明度単調・隣接ΔL≥0.06・単一色相・淡端 2.11 / 2.13）
 *   ink とランプのコントラスト  全10通り 4.5:1 以上（最小 5.35）
 * ⚠️ 淡端（ライト #d9a892 2.11 / ダーク #6b3a24 2.13）は面との対比 3:1 を割る。
 *    ヒートのセルは数字を直接載せていて #heat の表そのものが table view なので、
 *    dataviz の要求する relief channel は満たしている。
 *    ただし**純白系の面が前提**。セクション背景をグレーにしないこと。
 */
export type Theme = 'light' | 'dark';

/** スコア（＝需要のうち受け皿に入れない割合 %）の下限。5段 */
export const BINS = [0, 3, 8, 15, 30] as const;

/** 凡例の文言。ビンと同じ並び */
export const BIN_LABELS = [
  '〜3%（ほぼ全員入れる）',
  '3〜8%',
  '8〜15%',
  '15〜30%',
  '30%〜',
] as const;

export interface Palette {
  /** ビン0＝ティール（入りやすい）、ビン1〜4＝暖色の濃淡（不足の量） */
  ramp: string[];
  /** ramp と対になる文字色（セルの数字用） */
  ink: string[];
  /** score が null（データなし）の色。0点と同じ色にしないこと */
  nodata: string;
}

export const PALETTES: Record<Theme, Palette> = {
  // 明るい面：ビン0＝青、不足側は淡→濃
  light: {
    // 🔴 ramp[0] は styles.css の --accent と同じ値。「全員入れる」を指す青を
    //    地図と UI（#choose の「どの年も全員入れる」等）で1色に揃えている。片方だけ変えないこと
    ramp: ['#1c5cab', '#d9a892', '#c07a5c', '#9c5238', '#70331f'],
    // 🔴 単調ではない。ランプの明度カーブに合わせて対で持つ（固定条件で分岐しないこと）
    ink: ['#ffffff', '#0b0b0b', '#0b0b0b', '#ffffff', '#ffffff'],
    nodata: '#ecece8',
  },
  // 暗い面：ビン0＝青（面上で最も明るい）、不足側は暗→明
  dark: {
    ramp: ['#cde2fb', '#6b3a24', '#93552f', '#b3784d', '#c99a72'],
    ink: ['#0b0b0b', '#ffffff', '#ffffff', '#0b0b0b', '#0b0b0b'],
    nodata: '#1e1e22',
  },
};

/** スコア → ビン番号（0〜4） */
export function binOf(score: number): number {
  let i = 0;
  for (const b of BINS) if (score >= b) i++;
  return Math.max(0, i - 1);
}

/** スコア → 塗り色。null は「データなし」で nodata を返す（🔴 0点と同じ色にしない） */
export function fillOf(score: number | null, p: Palette): string {
  return score === null ? p.nodata : p.ramp[binOf(score)];
}
